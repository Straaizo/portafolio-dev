const revealObserver = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.08 });

// las tarjetas se generan dinámicamente, hay que esperar a que estén en el DOM
setTimeout(() => {
  document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));
}, 80);

/* ── EFECTO DE ESCRITURA ───────────────────────────────────── */
const nameToType   = "Enzo Sabattini";
const typingEl     = document.getElementById("typing-name");
let   charIndex    = 0;
let   isDeleting   = false;

function typeEffect() {
  if (!isDeleting) {
    typingEl.textContent = nameToType.substring(0, charIndex + 1);
    charIndex++;
    if (charIndex === nameToType.length) {
      // pausa antes de empezar a borrar
      isDeleting = true;
      setTimeout(typeEffect, 2200);
      return;
    }
  } else {
    typingEl.textContent = nameToType.substring(0, charIndex - 1);
    charIndex--;
    if (charIndex === 0) {
      // pausa antes de volver a escribir
      isDeleting = false;
      setTimeout(typeEffect, 600);
      return;
    }
  }
  setTimeout(typeEffect, isDeleting ? 70 : 140);
}

window.addEventListener('load', () => setTimeout(typeEffect, 900));

