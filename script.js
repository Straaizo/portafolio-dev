/* ── SECCIÓN ACTIVA EN LA BARRA DE NAVEGACIÓN ─────────────── */
const sections  = document.querySelectorAll('section[id]');
const navLinks  = document.querySelectorAll('.nav-link');

const sectionObserver = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      navLinks.forEach(l => l.classList.remove('active'));
      const match = document.querySelector(`.nav-link[href="#${entry.target.id}"]`);
      if (match) match.classList.add('active');
    }
  });
}, { threshold: 0.4 });

sections.forEach(s => sectionObserver.observe(s));

/* ── GALERÍA DE IMÁGENES ───────────────────────────────────── */
const modal        = document.getElementById("modal");
const modalImg     = document.getElementById("modalImg");
const modalCounter = document.getElementById("modal-counter");
const closeBtn     = document.getElementById("closeModal");
const prevBtn      = document.getElementById("prev");
const nextBtn      = document.getElementById("next");

let currentProject = 0;
let currentImage   = 0;

// caché de imágenes precargadas para evitar espera en cada cambio
const cacheImagenes = {};

function precargar(src) {
  if (!cacheImagenes[src]) {
    const img = new Image();
    img.src = src;
    cacheImagenes[src] = img;
  }
}

function precargarAdyacentes() {
  const imgs = proyectos[currentProject].imagenes;
  const siguiente = (currentImage + 1) % imgs.length;
  const anterior  = (currentImage - 1 + imgs.length) % imgs.length;
  precargar(imgs[siguiente]);
  precargar(imgs[anterior]);
}

function actualizarGaleria() {
  const imgs = proyectos[currentProject].imagenes;
  const src  = imgs[currentImage];

  modalCounter.textContent = `${currentImage + 1} / ${imgs.length}`;
  modalImg.alt = `${proyectos[currentProject].titulo} — imagen ${currentImage + 1}`;

  // si ya está en caché aparece al instante, si no hace fade al cargar
  if (cacheImagenes[src]?.complete) {
    modalImg.src     = src;
    modalImg.style.opacity = '1';
  } else {
    modalImg.style.opacity = '0';
    precargar(src);
    cacheImagenes[src].onload = () => {
      modalImg.src           = src;
      modalImg.style.opacity = '1';
    };
  }

  precargarAdyacentes();
}

function abrirGaleria(indiceProyecto) {
  currentProject = indiceProyecto;
  currentImage   = 0;

  // precargar todas las imágenes del proyecto en segundo plano
  proyectos[currentProject].imagenes.forEach(precargar);

  actualizarGaleria();
  modal.classList.remove("hidden");
  modal.classList.add("flex");
  document.body.style.overflow = "hidden";
}

function cerrarGaleria() {
  modal.classList.add("hidden");
  modal.classList.remove("flex");
  document.body.style.overflow = "";
}

// abrir al hacer clic en la imagen de una tarjeta
document.addEventListener("click", e => {
  const img = e.target.closest("img[data-index]") || (e.target.tagName === "IMG" && e.target.dataset.index !== undefined ? e.target : null);
  if (img && img.dataset.index !== undefined) {
    abrirGaleria(parseInt(img.dataset.index));
  }
});

// también abrir al hacer clic en el área de imagen de la tarjeta
document.getElementById('grid-proyectos').addEventListener('click', e => {
  const imgEl = e.target.closest('.h-48');
  if (imgEl) {
    const card  = imgEl.closest('[class*="group"]');
    const cards = Array.from(document.querySelectorAll('#grid-proyectos > div'));
    const idx   = cards.indexOf(card);
    if (idx !== -1) abrirGaleria(idx);
  }
});

closeBtn.onclick = cerrarGaleria;

// cerrar al hacer clic fuera de la imagen
modal.addEventListener("click", e => {
  if (e.target === modal) cerrarGaleria();
});

nextBtn.onclick = () => {
  currentImage = (currentImage + 1) % proyectos[currentProject].imagenes.length;
  actualizarGaleria();
};

prevBtn.onclick = () => {
  currentImage = (currentImage - 1 + proyectos[currentProject].imagenes.length) % proyectos[currentProject].imagenes.length;
  actualizarGaleria();
};

// navegación con teclado: flechas para cambiar imagen, Escape para cerrar
document.addEventListener("keydown", e => {
  if (modal.classList.contains("hidden")) return;
  if (e.key === "ArrowRight" || e.key === "ArrowDown") nextBtn.click();
  if (e.key === "ArrowLeft"  || e.key === "ArrowUp")   prevBtn.click();
  if (e.key === "Escape")                               cerrarGaleria();
});
